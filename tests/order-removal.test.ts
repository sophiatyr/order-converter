import assert from 'node:assert/strict';
import fs from 'node:fs';
import {emptyWorkspace,loadWorkspace,upsertOrder} from '../src/utils/workspace';
import {removeOrder,restoreRemovedOrder} from '../src/utils/orderRemoval';
const source=JSON.parse(fs.readFileSync('public/csq-workspace-references.json','utf8')).orders[0];
const initial={...upsertOrder(emptyWorkspace(),source),tracking:{test:{status:'生產中'}},productNotes:{TEST:{brand:'ABC',season:'SS27',remarks:'保留'}}};
const removed=removeOrder(initial,source.poNumber);
assert.equal(removed.orders.length,0);assert.deepEqual(removed.removedOrders![source.poNumber],initial.orders[0]);assert.equal(initial.orders.length,1);
assert.equal(removed.tracking,initial.tracking);assert.equal(removed.productNotes,initial.productNotes);
const reopened=loadWorkspace(JSON.stringify(removed),source);
assert.equal(reopened.orders.length,0,'A cached active order must not resurrect a removed PO on reload');
const restored=restoreRemovedOrder(reopened,source.poNumber);
assert.deepEqual(restored.orders[0],initial.orders[0]);assert.equal(Object.keys(restored.removedOrders!).length,0);
const fresh=upsertOrder(removed,{...source,brand:'NEW BRAND'});
assert.equal(fresh.orders.length,1);assert.equal(fresh.orders[0].brand,'NEW BRAND');assert.equal(Object.keys(fresh.removedOrders!).length,0,'Re-importing clears the stale removed version');
assert.throws(()=>restoreRemovedOrder({...removed,orders:initial.orders},source.poNumber),/重新匯入/);
assert.throws(()=>removeOrder({...initial,shipments:[{poNumber:source.poNumber} as any]},source.poNumber),/出貨批次/);
assert.throws(()=>loadWorkspace(JSON.stringify({...removed,removedOrders:{WRONG:source}}),null));
console.log('PASS: reversible order removal, reload protection, restore/re-import precedence, preserved tracking/products and linked-shipment protection.');
