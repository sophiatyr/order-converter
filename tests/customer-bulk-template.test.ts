import assert from 'node:assert/strict';
import fs from 'node:fs';
import {customerTemplatePayload,customerTemplatePreview} from '../src/utils/customerBulkTemplate';
import {completeCustomerRows,poColorItemNumber} from '../src/utils/trackingDocuments';
import {emptyWorkspace,trackingRows,type ReferenceSnapshot} from '../src/utils/workspace';
const refs=JSON.parse(fs.readFileSync('public/csq-workspace-references.json','utf8')) as ReferenceSnapshot;
const source=trackingRows(emptyWorkspace(),refs).find(r=>r.poNumber==='26OF028471'&&r.itemNo==='ABCTM030CO')!;
const colors=completeCustomerRows([source],refs.orders),payload=customerTemplatePayload(colors,'2026-10-19');
assert.deepEqual(customerTemplatePreview(colors,'2026-10-19').rows,payload.rows,'Web preview uses exactly the export values');
const unknown={...colors[0],supplier:'UNMAPPED',supplierCode:'UNMAPPED',supplierName:'',internalFields:{},bulk:{factoryName:''}};
assert.equal(customerTemplatePreview([unknown],'2026-10-19').missingFactories.length,1,'Missing English names remain visible in preview');
assert.throws(()=>customerTemplatePayload([unknown],'2026-10-19'),/英文名稱/);
assert.equal(payload.rows.length,colors.length);assert.equal(payload.week,46314);
assert.equal(payload.rows.reduce((n,row)=>n+Number(row[8]),0),source.quantity);
assert.equal(payload.rows[0][2],source.itemNo);assert.equal(payload.rows[0][4],source.poNumber);
assert.deepEqual(payload.rows.map(r=>r[11]),['ABCTM030CO-001','ABCTM030CO-050','ABCTM030CO-254']);
const first=refs.orders!.find(o=>o.poNumber==='26OF028471')!.items[0];
assert.equal(poColorItemNumber({...first,vendorPart:'ABCTM030CO-1001'},'001'),'ABCTM030CO-001','Do not reuse a different colour with the same suffix');
assert.equal(poColorItemNumber({...first,itemNo:'AFU881S27',vendorPart:'AFU881S27/001-050'},'001/050'),'AFU881S27/001-050','Preserve PO separator and leading zeros');
assert.ok(payload.rows.every(row=>row[0]==='SPORTS KITE'));
assert.ok(payload.rows.every(row=>typeof row[9]==='string'&&!/[\u3400-\u9fff]/.test(row[9] as string)));
const needsEnglish={...colors[0],bulk:{...colors[0].bulk,factoryName:'中文工廠'}};
assert.equal(customerTemplatePayload([needsEnglish],'2026-10-19',[source]).rows[0][9],source.bulk?.factoryName);
assert.equal(payload.rows[0][31],null,'Never send a replacement formula or cached overall-check value');
assert.equal(payload.rows[0][14],source.bulk?.tpStatus);assert.equal(payload.rows[0][30],source.bulk?.fabricTestStatus);
assert.equal(typeof payload.rows[0][6],'number','Excel dates are serial values');
assert.throws(()=>customerTemplatePayload(colors,'2026-02-30'));
assert.throws(()=>customerTemplatePayload(Array.from({length:996},()=>colors[0]),'2026-10-19'),/995/);
console.log('PASS original customer template payload: exact 45-column mapping, protected formula untouched, source quantities, date types and template capacity.');
