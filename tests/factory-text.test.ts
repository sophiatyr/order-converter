import assert from 'node:assert/strict';
import fs from 'node:fs';
import ExcelJS from 'exceljs';
import {factoryText,saveFactoryText} from '../src/utils/factoryText';
import {emptyWorkspace,loadWorkspace,upsertOrder} from '../src/utils/workspace';
import {withErpPiMaterials} from '../src/utils/piMaterials';
import {parseGridToOrder} from '../src/utils/localPoParser';
import {buildReferenceDocument} from '../src/utils/referenceDocuments';
import {applyErpProducts,productQuotes,erpQuoteKey,erpFactoryOrders} from '../src/utils/erpProducts';
const pages=JSON.parse(fs.readFileSync('tests/fixtures/csq-tennis-1636-rows.json','utf8'));
const order=parseGridToOrder([['Order number','26OF001636'],['Vendor part number','Description'],...pages.flatMap((page:string[][])=>[[],...page])]).order!;
const erp=JSON.parse(fs.readFileSync('public/erp-products.json','utf8'));
const templates=JSON.parse(fs.readFileSync('public/csq-document-templates.json','utf8'));
const choices=Object.fromEntries(erp.products.filter((p:any)=>order.items.some(i=>i.itemNo===p.itemNo)).map((p:any)=>[p.itemNo,erpQuoteKey(productQuotes(p).find(q=>q.supplierCode==='RJ')!)]));
const applied=erpFactoryOrders(applyErpProducts(order,erp,choices).order)[0].order;
const style=applied.items[0].itemNo,w=emptyWorkspace();
const product=saveFactoryText(applied,w,style,{chineseName:'測試運動上衣',chineseSpec:'主布：測試聚酯纖維'},true);
assert.ok(product.order.items.filter(i=>i.itemNo===style).every(i=>!i.factoryText));
assert.equal(product.workspace.productNotes[style].chineseName,'測試運動上衣');
assert.equal(product.workspace.productNotes[style].spec,undefined,'Chinese material must never enter the English material field');
const local=saveFactoryText(product.order,product.workspace,style,{chineseName:'本單專用上衣',chineseSpec:''},false);
assert.equal(local.workspace,product.workspace);
assert.ok(local.order.items.filter(i=>i.itemNo===style).every(i=>i.factoryText?.chineseName==='本單專用上衣'));
assert.equal(factoryText(local.order.items[0],local.workspace.productNotes[style]).chineseSpec,'','An empty order-specific translation stays omitted');
assert.equal(loadWorkspace(JSON.stringify(upsertOrder(local.workspace,local.order)),null).orders[0].items[0].factoryText!.chineseName,'本單專用上衣');
const blank={...applied.items[0],chineseName:'',chineseSpec:''};
assert.ok(!/[\u3400-\u9fff]/.test(factoryText(blank).name));
const allText=(book:ExcelJS.Workbook)=>{const values:string[]=[];for(const ws of book.worksheets)ws.eachRow(row=>row.eachCell(cell=>{if(!cell.isMerged||cell.master.address===cell.address)values.push(cell.text);}));return values.join('\n');};
for(const kind of ['factory','quantity'] as const){
 const book=buildReferenceDocument(templates,kind,product.order,[],erp,product.workspace).book;
 const text=allText(book);assert.ok(text.includes('測試運動上衣'));assert.ok(text.includes('測試聚酯纖維'));
 const nameCell=book.worksheets.flatMap(ws=>{const cells:ExcelJS.Cell[]=[];ws.eachRow(row=>row.eachCell(cell=>{if(cell.text.includes('測試運動上衣'))cells.push(cell);}));return cells;})[0];
 assert.ok(nameCell.text.indexOf(applied.items[0].styleName)<nameCell.text.indexOf('測試運動上衣'),'English name precedes Chinese');
 const restored=new ExcelJS.Workbook();await restored.xlsx.load(await book.xlsx.writeBuffer());assert.equal(allText(restored),text);
}
assert.ok(!allText(buildReferenceDocument(templates,'pi',product.order,[],erp,product.workspace).book).includes('測試運動上衣'));
assert.ok(!allText(buildReferenceDocument(templates,'pi',product.order,[],erp,product.workspace).book).includes('測試聚酯纖維'));
assert.equal(withErpPiMaterials(local.order,erp).items[0].factoryText!.chineseName,'本單專用上衣');
assert.deepEqual(order.items.map(i=>[i.description,i.totalQuantity,i.unitPriceUSD]),applied.items.map(i=>[i.description,i.totalQuantity,i.unitPriceUSD]));
console.log('PASS: per-style bilingual factory/quantity documents, English-first order, absent Chinese omission, master vs order scope, backups, XLSX round trips and unchanged P/I English.');
