import assert from 'node:assert/strict';
import ExcelJS from 'exceljs';
import {applyErpProducts, erpFactoryOrders, erpQuoteKey, type ErpQuote, type ErpProduct} from '../src/utils/erpProducts';
import {parseTextToOrder} from '../src/utils/localPoParser';
import {factoryDocument} from '../src/utils/csqAccount';
import {buildFactoryPOSheet} from '../src/utils/excelExport';
const order=parseTextToOrder('PO No: 26OF000337\nItem\tS\tM\tQty\tPrice\nABCRM1039W26\t80\t190\t270\t2.10\nABCRW1036W26\t60\t170\t230\t2.00').order!;
const product=(itemNo:string,price:number):ErpProduct=>({itemNo,chineseName:'ERP 原品名',chineseSpec:'ERP 多行規格\n第二行',supplierCode:'LA',factorySupplier:'ERP 工廠',factoryCurrency:'RMB',factoryPrice:price,uom:'PC',issue:'',quoteDate:'20251224'});
const snapshot={account:'CSQ' as const,updatedAt:'2026-10-06',products:[product('ABCRM1039W26',12.5),product('ABCRW1036W26',11.5)]};
const result=applyErpProducts(order,snapshot);
assert.equal(result.matched,2); assert.deepEqual(result.issues,[]);
assert.equal(result.order.factorySupplier,'ERP 工廠'); assert.equal(result.order.supplierCode,'LA');
assert.equal(result.order.factoryCurrency,'RMB');
assert.equal(result.order.items[0].unitPriceRMB,12.5); assert.equal(result.order.items[1].unitPriceRMB,11.5);
assert.equal(result.order.items[0].unitPriceUSD,2.1); assert.equal(result.order.totalAmountUSD,order.totalAmountUSD);
assert.deepEqual(result.order.items[0].colors,order.items[0].colors);
assert.notEqual(order.items[0].chineseName,'ERP 原品名');
const workbook=new ExcelJS.Workbook(); const sheet=workbook.addWorksheet('採購單');
buildFactoryPOSheet(sheet,factoryDocument(result.order),{poCurrency:'RMB'});
const values:unknown[]=[]; sheet.eachRow(r=>r.eachCell(c=>values.push(c.value)));
assert.ok(values.includes(12.5)); assert.ok(values.includes(11.5)); assert.ok(values.some(v=>typeof v==='string'&&v.includes('ERP 原品名')));
const mixed=applyErpProducts(order,{...snapshot,products:[snapshot.products[0],{...snapshot.products[1],supplierCode:'OTHER'}]});
assert.equal(mixed.matched,2); assert.equal(mixed.order.factorySupplier,order.factorySupplier);
assert.equal(erpFactoryOrders(mixed.order).length,2);
const unresolved=applyErpProducts(order,{...snapshot,products:[snapshot.products[0],{...snapshot.products[1],issue:'多筆報價'}]});
assert.equal(unresolved.matched,1); assert.equal(erpFactoryOrders(unresolved.order)[0].order.items.length,1);
const prefix=applyErpProducts(order,{...snapshot,products:[{...snapshot.products[0],itemNo:'ABCRM1039'},snapshot.products[1]]});
assert.equal(prefix.matched,1); assert.ok(prefix.issues.some(i=>i.includes('查無')));
const usd=applyErpProducts(order,{...snapshot,products:snapshot.products.map(p=>({...p,factoryCurrency:'USD',factoryPrice:1.5}))});
assert.equal(factoryDocument(usd.order).items[0].unitPriceUSD,1.5); assert.equal(usd.order.items[0].unitPriceUSD,2.1);
const accessories=parseTextToOrder('PO No: 26OF001421\nItem\tS\tQty\tPrice\nABCRA08\t1200\t1200\t2\nABCRA07\t500\t500\t3').order!;
const split=applyErpProducts(accessories,{...snapshot,products:[{...product('ABCRA08',1.6),factoryCurrency:'USD',supplierCode:'RJ'},{...product('ABCRA07',2.17),supplierCode:'HFQ',factoryCurrency:'USD',uom:'PR',purchaseUom:'PR',issue:'產品供應商報價單位與 PO 件數尚未確認換算'}]});
assert.equal(split.matched,2); assert.equal(split.order.totalPieces,1700);
const groups=erpFactoryOrders(split.order);
assert.equal(groups.length,2);
assert.equal(groups[0].order.totalAmountUSD,1920);
assert.equal(groups[1].order.totalAmountUSD,1085);
assert.equal(groups[1].order.factoryQuantityUnit,'雙');
assert.equal(groups[1].order.items[0].unitPriceUSD,3);
const pairSheet=workbook.addWorksheet('手套');buildFactoryPOSheet(pairSheet,factoryDocument(groups[1].order),{poCurrency:'USD'});
const pairValues:unknown[]=[];pairSheet.eachRow(r=>r.eachCell(c=>pairValues.push(c.value)));
assert.ok(pairValues.includes('總 數\n(雙)'));assert.ok(pairValues.includes(2.17));assert.ok(pairValues.includes(1085));
const oldQuote:ErpQuote={supplierCode:'LA',factorySupplier:'ERP 工廠',factoryCurrency:'RMB',factoryPrice:12.5,purchaseUom:'PC',quoteDate:'20260129'};
const newQuote:ErpQuote={...oldQuote,factoryPrice:14,quoteDate:'20260723'};
const ambiguous={...snapshot,products:[{...snapshot.products[0],supplierCode:'',factorySupplier:'',factoryPrice:null,issue:'多筆報價',quotes:[oldQuote,newQuote]},snapshot.products[1]]};
assert.equal(applyErpProducts(order,ambiguous).matched,1);
const chosen=applyErpProducts(order,ambiguous,{'ABCRM1039W26':erpQuoteKey(newQuote)});
assert.equal(chosen.matched,2);
assert.equal(chosen.order.items[0].unitPriceRMB,14);
assert.equal(chosen.order.items[0].factoryProduct!.quoteDate,'20260723');
assert.equal(chosen.order.items[0].unitPriceUSD,2.1);
assert.deepEqual(chosen.order.items[0].colors,order.items[0].colors);
assert.equal(applyErpProducts(chosen.order,ambiguous).order.items[0].unitPriceRMB,14);
const cleared=applyErpProducts(chosen.order,ambiguous,{'ABCRM1039W26':''});
assert.equal(cleared.order.items[0].factoryProduct,undefined);
assert.equal(cleared.order.items[0].erpQuoteKey,undefined);
const removed=applyErpProducts(chosen.order,{...ambiguous,products:[{...ambiguous.products[0],quotes:[oldQuote]},ambiguous.products[1]]});
assert.deepEqual(removed.order.items[0].factoryProduct,chosen.order.items[0].factoryProduct);
const explicitMissing=applyErpProducts(chosen.order,{...ambiguous,products:[{...ambiguous.products[0],quotes:[oldQuote]},ambiguous.products[1]]},{ABCRM1039W26:erpQuoteKey(newQuote)});
assert.equal(explicitMissing.order.items[0].factoryProduct,undefined);assert.ok(explicitMissing.issues.some(i=>i.includes('已不存在')));
const invalidQuote={...newQuote,purchaseUom:'BOX'};
assert.equal(applyErpProducts(order,{...ambiguous,products:[{...ambiguous.products[0],quotes:[invalidQuote]},ambiguous.products[1]]},{ABCRM1039W26:erpQuoteKey(invalidQuote)}).order.items[0].factoryProduct,undefined);
const twoColors={...order,items:[order.items[0],{...order.items[0],id:'another-color'},order.items[1]]};
const both=applyErpProducts(twoColors,ambiguous,{ABCRM1039W26:erpQuoteKey(oldQuote)});
assert.equal(both.matched,3);assert.ok(both.order.items.slice(0,2).every(i=>i.factoryProduct?.price===12.5));
assert.equal(applyErpProducts(twoColors,ambiguous).issues.filter(i=>i.startsWith('ABCRM1039W26')).length,1);
console.log('PASS: ERP exact product matching, supplier/currency quote integrity, partial/ambiguous quote protection, preserved customer prices and factory Excel costs.');
