      if (values[field] === void 0) continue;
      const value = field === "itemNo" ? values[field].trim().toUpperCase() : values[field];
      if (field === "itemNo" && !value) throw new Error("\u6B3E\u865F\u4E0D\u80FD\u7A7A\u767D");
