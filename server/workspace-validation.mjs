var DB_STORAGE_KEY = "SK_PRODUCT_MAPPING_DB_V2";
function getStoredProducts() {
  try {
    if (typeof window !== "undefined" && typeof localStorage !== "undefined") {
      const raw = localStorage.getItem(DB_STORAGE_KEY);
      if (raw) {
        const parsed = JSON.parse(raw);
        if (Array.isArray(parsed) && parsed.length > 0) {
          return parsed;
        }
      }
    }
  } catch (e) {
    console.error("Error reading product database from localStorage", e);
  }
  return defaultProductDatabase;
}
function matchProductInDatabase(itemNo) {
  if (!itemNo) return void 0;
  const products = getStoredProducts();
  const cleanTarget = itemNo.trim().toUpperCase();
  const exact = products.find((p) => p.itemNo.trim().toUpperCase() === cleanTarget);
  if (exact) return exact;
  const prefixMatch = products.find(
    (p) => cleanTarget.startsWith(p.itemNo.trim().toUpperCase()) || p.itemNo.trim().toUpperCase().startsWith(cleanTarget)
  );
  if (prefixMatch) return prefixMatch;
  return void 0;
}

